export function callForwardingProvidersForType(lineType) {
  return CALL_FORWARDING_PROVIDERS.filter((provider) => provider.lineTypes.includes(lineType));
}

export function callForwardingProvider(providerId) {
  return CALL_FORWARDING_PROVIDERS.find((provider) => provider.id === providerId) || null;
}

export function renderForwardingTemplate(value, line = {}) {
  const digits = String(line.destinationNumber || "").replace(/\D/g, "");
  const destination10 = digits.length > 10 ? digits.slice(-10) : digits;
  const destination11 = destination10 ? `1${destination10}` : "";
  const destinationE164 = destination10 ? `+1${destination10}` : "";
  const replacements = {
    destination10,
    destination11,
    destinationE164,
    delaySeconds: String(line.delaySeconds || 20),
    ringCount: String(line.ringCount || 4),
  };
  return String(value || "").replace(/\{\{(destination10|destination11|destinationE164|delaySeconds|ringCount)\}\}/g, (_, key) => replacements[key]);
}
